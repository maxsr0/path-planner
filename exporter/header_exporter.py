import os
from datetime import datetime


def export_trajectory_header(trajectory, filepath, array_name=None):
    if array_name is None:
        base = os.path.splitext(os.path.basename(filepath))[0]
        array_name = base.upper().replace(' ', '_').replace('-', '_')

    guard = array_name + "_HPP"
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    count = len(trajectory)

    lines = [
        f"// Auto-generated by PRISM Path Planner  {timestamp}",
        f"// {count} points — include this file and pass {array_name} to chassis.follow_trajectory()",
        "",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        '#include "PRISM/auton/traj_loader.h"',
        "#include <array>",
        "",
        f"constexpr std::array<TrajectoryPoint, {count}> {array_name} = {{{{",
    ]

    for i, pt in enumerate(trajectory):
        x, y, v, t = pt
        comma = "," if i < count - 1 else ""
        lines.append(f"    {{{{ {x:.6f}f, {y:.6f}f, {v:.6f}f, {t:.6f}f }}}}{comma}")

    lines += [
        "}};",
        "",
        f"#endif // {guard}",
        "",
    ]

    with open(filepath, 'w') as f:
        f.write('\n'.join(lines))
