import os
import re
from datetime import datetime

# Header in the PRISM firmware template that defines Point / TrajectoryPoint.
FIRMWARE_INCLUDE = "PRISM/auton/traj_loader.h"


def make_identifier(name):
    """Turn an arbitrary string into a valid C++ identifier (upper-case)."""
    ident = re.sub(r'[^A-Za-z0-9_]', '_', name).upper()
    if not ident or ident[0].isdigit():
        ident = "PATH_" + ident
    return ident


def export_trajectory_header(trajectory, filepath, array_name=None, standalone=False):
    """Write trajectory as a constexpr std::array<TrajectoryPoint, N>.

    By default the header includes the firmware's traj_loader.h for the type
    definitions. With standalone=True it defines Point/TrajectoryPoint inline
    instead (for use outside the PRISM template); do not mix the two modes in
    one translation unit.
    """
    if array_name is None:
        array_name = os.path.splitext(os.path.basename(filepath))[0]
    array_name = make_identifier(array_name)

    guard = array_name + "_HPP"
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    count = len(trajectory)

    lines = [
        f"// Auto-generated by PRISM Path Planner  {timestamp}",
        f"// {count} points. Pass {array_name} to your trajectory follower to use",
        "",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "#include <array>",
    ]

    if standalone:
        lines += [
            "",
            "#ifndef TRAJECTORY_POINT_DEFINED",
            "#define TRAJECTORY_POINT_DEFINED",
            "struct Point { float x; float y; };",
            "struct TrajectoryPoint { Point pos; float velocity; float timestamp; };",
            "#endif",
        ]
    else:
        lines.append(f'#include "{FIRMWARE_INCLUDE}"')

    lines += [
        "",
        f"constexpr std::array<TrajectoryPoint, {count}> {array_name} = {{{{",
    ]

    for i, pt in enumerate(trajectory):
        x, y, v, t = pt
        comma = "," if i < count - 1 else ""
        # { {x, y}, velocity, timestamp } matches TrajectoryPoint { Point pos; float velocity; float timestamp; }
        lines.append(f"    {{ {{ {x:.6f}f, {y:.6f}f }}, {v:.6f}f, {t:.6f}f }}{comma}")

    lines += [
        "}};",
        "",
        f"#endif // {guard}",
        "",
    ]

    with open(filepath, 'w', newline='\n') as f:
        f.write('\n'.join(lines))
